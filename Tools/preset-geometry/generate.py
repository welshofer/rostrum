#!/usr/bin/env python3
"""Generate Sources/Rostrum/Schema/GeneratedPresetShapes.swift.

Input is presetShapeDefinitions.xml from the ECMA-376 Part 1 (5th edition)
download: OfficeOpenXML-DrawingMLGeometries.zip inside
https://ecma-international.org/wp-content/uploads/ECMA-376-1_5th_edition_december_2016.zip

    python3 Tools/preset-geometry/generate.py /path/to/presetShapeDefinitions.xml

Only what a renderer needs is kept: adjustment defaults, guides, the text
rectangle and the paths. Adjust handles and connection sites are dropped.
Presets that SVGPresetGeometry already draws analytically are skipped.
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

NS = "{http://schemas.openxmlformats.org/drawingml/2006/main}"
ROOT = pathlib.Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "Sources/Rostrum/Schema/GeneratedPresetShapes.swift"
ANALYTIC = ROOT / "Sources/Rostrum/Presentation/SVGPresetGeometry.swift"


def analytic_presets():
    source = ANALYTIC.read_text()
    block = re.search(r"static let analytic: Set<String> = \[(.*?)\]", source, re.S).group(1)
    return set(re.findall(r'"(\w+)"', block))


ARITY = {"val": 1, "*/": 3, "+-": 3, "+/": 3, "?:": 3, "abs": 1, "min": 2, "max": 2, "sqrt": 1,
         "pin": 3, "mod": 3, "sin": 2, "cos": 2, "tan": 2, "at2": 2, "cat2": 3, "sat2": 3}


def formula(text):
    # The published circular-arrow definitions carry a stray fourth operand
    # ("+- xH 0 dxB 0"). Operators take a fixed number; drop the excess.
    tokens = text.split()
    assert len(tokens) - 1 >= ARITY[tokens[0]], text
    return " ".join(tokens[:ARITY[tokens[0]] + 1])


def compact(element):
    tag = "a:" + element.tag.replace(NS, "")
    attributes = "".join(
        f' {name}="{formula(value) if name == "fmla" else value}"'
        for name, value in element.attrib.items() if name != "extrusionOk")
    children = "".join(compact(child) for child in element)
    return f"<{tag}{attributes}>{children}</{tag}>" if children else f"<{tag}{attributes}/>"


def main():
    root = ET.parse(sys.argv[1]).getroot()
    skip = analytic_presets()
    definitions = {}
    for shape in root:
        name = shape.tag
        if name in skip:
            continue
        parts = [compact(child) for child in shape
                 if child.tag in {NS + "avLst", NS + "gdLst", NS + "rect", NS + "pathLst"}]
        body = "".join(parts)
        # The published file names two definitions "upDownArrow"; the first is
        # upArrow. Keep the genuine one (it has the larger outline).
        if name not in definitions or len(body) > len(definitions[name]):
            definitions[name] = body
    lines = [
        "// Generated by Tools/preset-geometry/generate.py from ECMA-376 Part 1",
        "// (5th edition) presetShapeDefinitions.xml. Do not edit by hand.",
        "// © Ecma International; see THIRD_PARTY_LICENSES.md.",
        "",
        "/// Preset shape definitions in DrawingML custom-geometry form, for the",
        "/// presets `SVGPresetGeometry` does not draw analytically.",
        "enum GeneratedPresetShapes {",
        "    static let definitions: [String: String] = [",
    ]
    for name in sorted(definitions):
        assert '"#' not in definitions[name]
        lines.append(f'        "{name}": #"{definitions[name]}"#,')
    lines += ["    ]", "}", ""]
    OUTPUT.write_text("\n".join(lines))
    print(f"{len(definitions)} definitions, {OUTPUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
